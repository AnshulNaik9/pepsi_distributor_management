// We use route name to check if the route already is seeded
const existingRoutes = db.prepare('SELECT name FROM routes').all().map(r => r.name);

let insertedRoutes = 0;
let insertedCustomers = 0;

const insertRoute = db.prepare('INSERT INTO routes (name) VALUES (?)');
const insertCustomer = db.prepare(
  'INSERT INTO customers (name, phone, address, route_id, credit_balance) VALUES (?, ?, ?, ?, 0)'
);

const insertAll = db.transaction(() => {
  for (const route of routesData) {
    if (existingRoutes.includes(route.name)) {
      console.log(`  Route already exists, skipping: ${route.name}`);
      const existing = db.prepare('SELECT id FROM routes WHERE name = ?').get(route.name);
      // Still add customers if they don't exist
      for (const c of route.customers) {
        const exists = db.prepare('SELECT 1 FROM customers WHERE name = ? AND route_id = ?').get(c.name, existing.id);
        if (!exists) {
          insertCustomer.run(c.name, c.phone || '0', c.address, existing.id);
          insertedCustomers++;
        }
      }
      continue;
    }
    const result = insertRoute.run(route.name);
    const routeId = result.lastInsertRowid;
    insertedRoutes++;
    console.log(`  Added route: ${route.name} (id: ${routeId})`);

    for (const c of route.customers) {
      insertCustomer.run(c.name, c.phone || '0', c.address, routeId);
      insertedCustomers++;
    }
  }
});

console.log('\n=== CS Marketing Customer Seed ===');
insertAll();
